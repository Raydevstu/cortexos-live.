declare global {
  var __cortexToolRegistry: ToolRegistry | undefined;
}

export function createConfiguredToolRegistry(): ToolRegistry {
  const registry = new ToolRegistry();
  registerGitHubTools(registry);
  registerFilesystemTools(registry);
  registerDocumentationTools(registry);
  registerTerminalTools(registry);
  return registry;
}

export function getToolRegistry(): ToolRegistry {
  if (!global.__cortexToolRegistry) {
    global.__cortexToolRegistry = createConfiguredToolRegistry();
  }
  return global.__cortexToolRegistry;
}

/**
 * Maps a studio's objective or command to the best default registered tool for Studio Tool Integration
 * across Design, Architecture, Development, QA, Discovery, Product, Release, Librarian, and Jarvis.
 */
export function selectDefaultStudioTool(
  studioId: string,
  objective: string
): { toolName: string; parameters: Record<string, unknown> } {
  const lower = objective.toLowerCase();
  const sid = studioId.toLowerCase();

  if (lower.includes("branch")) {
    return {
      toolName: "github.branch_manage",
      parameters: { action: "create", branchName: `feat/${sid}-worktree` },
    };
  }
  if (lower.includes("commit")) {
    return {
      toolName: "github.commit_create",
      parameters: { message: `feat(${sid}): ${objective.slice(0, 64)}` },
    };
  }
  if (lower.includes("pr") || lower.includes("pull request")) {
    return {
      toolName: "github.pr_create",
      parameters: {
        title: `feat(${sid}): ${objective.slice(0, 56)}`,
        sourceBranch: `feat/${sid}-sprint8`,
        targetBranch: "main",
        description: objective,
      },
    };
  }
  if (lower.includes("openapi") || lower.includes("api spec") || lower.includes("contract")) {
    return {
      toolName: "docs.openapi_read",
      parameters: { serviceName: sid === "architecture" ? "studio-service" : "jarvis-service" },
    };
  }
  if (lower.includes("wiki") || lower.includes("knowledge") || sid === "librarian") {
    return {
      toolName: "docs.wiki_read",
      parameters: { pathOrQuery: "" },
    };
  }
  if (lower.includes("search") || lower.includes("repo")) {
    return {
      toolName: "github.repo_search",
      parameters: { query: "CortexOS" },
    };
  }

  if (sid === "design") {
    return {
      toolName: "fs.artifact_export",
      parameters: {
        title: `Design Spec: ${objective.slice(0, 44)}`,
        artifactType: "wireframe",
        exportSubdir: "exports/design",
        content: [
          `# Design Studio Specification — ${objective}`,
          "",
          "- **Surface Canvas:** `#090B0F` (18.33:1 WCAG AAA)",
          "- **Elevated Drawer:** `#11151D` (15.10:1 WCAG AAA)",
          "- **Primary Action:** `#00FFA3` (13.94:1 WCAG AAA)",
          "- **Grid Topology:** 12-col Desktop / 8-col Tablet / 4-col Mobile",
        ].join("\n"),
      },
    };
  }

  if (sid === "architecture") {
    return {
      toolName: "docs.openapi_read",
      parameters: { serviceName: "studio-service" },
    };
  }

  if (sid === "development") {
    const safeName = objective
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")
      .slice(0, 32);
    return {
      toolName: "github.file_write",
      parameters: {
        filePath: `src/${safeName || "feature-module"}.ts`,
        content: [
          `// Generated by CortexOS Development Studio`,
          `// Objective: ${objective}`,
          `export interface ExecutionModuleConfig {`,
          `  readonly studio: "development";`,
          `  readonly verified: boolean;`,
          `  readonly timestamp: string;`,
          `}`,
          `export const MODULE_CONFIG: ExecutionModuleConfig = {`,
          `  studio: "development",`,
          `  verified: true,`,
          `  timestamp: "${new Date().toISOString()}",`,
          `};`,
          "",
        ].join("\n"),
      },
    };
  }

  if (sid === "qa") {
    return {
      toolName: "terminal.exec",
      parameters: {
        command: "git status --short",
        workdir: ".",
      },
    };
  }

  if (sid === "release") {
    return {
      toolName: "github.pr_create",
      parameters: {
        title: `release: ${objective.slice(0, 48)}`,
        sourceBranch: "feat/release-candidate",
        targetBranch: "main",
        description: objective,
      },
    };
  }

  return {
    toolName: "docs.markdown_read",
    parameters: {
      filePath: "studios/design/mission.md",
    },
  };
}

